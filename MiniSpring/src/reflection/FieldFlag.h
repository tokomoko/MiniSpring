#pragma once

#include "../core/Core.h"

#include <cstdint>

constexpr uint32_t BIT(unsigned bit) { return 1u << bit; }

enum class FieldFlag : uint32_t {
  None = 0,

  PrimaryKey = BIT(0),
  AutoGenerated = BIT(1),
  Nullable = BIT(2),
  Unique = BIT(3),
  Indexed = BIT(4),

  Lazy = BIT(5),
  Transient = BIT(6),
  Version = BIT(7)
};

constexpr FieldFlag operator|(FieldFlag lhs, FieldFlag rhs) {
  return static_cast<FieldFlag>(static_cast<uint32_t>(lhs) |
                                static_cast<uint32_t>(rhs));
}

constexpr FieldFlag operator&(FieldFlag lhs, FieldFlag rhs) {
  return static_cast<FieldFlag>(static_cast<uint32_t>(lhs) &
                                static_cast<uint32_t>(rhs));
}

constexpr FieldFlag operator~(FieldFlag flag) {
  return static_cast<FieldFlag>(~static_cast<uint32_t>(flag));
}

constexpr FieldFlag operator|=(FieldFlag &lhs, FieldFlag rhs) {
  lhs = static_cast<FieldFlag>(static_cast<uint32_t>(lhs) |
                               static_cast<uint32_t>(rhs));
  return lhs;
}

constexpr FieldFlag operator&=(FieldFlag &lhs, FieldFlag rhs) {
  lhs = static_cast<FieldFlag>(static_cast<uint32_t>(lhs) &
                               static_cast<uint32_t>(rhs));
  return lhs;
}