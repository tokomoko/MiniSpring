#pragma once

#include "EntityDescriptorBase.h"

#include "../core/Core.h"

#include "../reflection/FieldFlag.h"
#include "../reflection/FieldMetadata.h"
#include "../reflection/TypeDescriptor.h"

#include <string>

template <typename T>
class EntityDescriptor : public EntityDescriptorBase {
 public:
  EntityDescriptor(std::string table, TypeDescriptor<T> type)
      : m_table(std::move(table)), m_type(std::move(type)) {}

  FieldBase &primaryKey() {
    for (auto &field : m_type.fields) {
      if (field->metadata().has(FieldFlag::PrimaryKey)) {
        return *field;
      }
    }

    throw std::runtime_error("Entity has no primary key");
  }

  FieldBase *autoGeneratedField() const {
    for (auto &field : m_type.fields) {
      if (field->metadata().has(FieldFlag::AutoGenerated)) return field.get();
    }
    return nullptr;
  }

  const std::string &table() const { return m_table; }

  TypeDescriptor<T> &type() { return m_type; }

 private:
  std::string m_table;
  TypeDescriptor<T> m_type;
};