#include"../database/QueryResult.h"
#include"../database/DatabaseException.h"
#include"../database/sqlite/SQLiteDatabase.h"
#include"../database/migration_manager/Migration.h"
#include"../database/migration_manager/MigrationManager.h"

#include"../reflection/FieldBase.h"
#include"../reflection/FieldInfo.h"
#include"../reflection/FieldMetadata.h"
#include"../reflection/TypeDescriptor.h"

#include"../orm/EntityDescriptor.h"
#include"../orm/EntityRegistry.h"
#include"../orm/EntityManager.h"
#include"../orm/Repository.h"

#include"../resource_manager/Platform.h"

#include <iostream>

struct User
{
	int id;
	std::string name;
	int age;
};

int main() {
	try {
		TypeDescriptor<User> userType;
		userType.addField(std::make_shared<FieldInfo<User, int>>("id", &User::id, FieldMetadata(FieldFlag::PrimaryKey | FieldFlag::AutoGenerated)));
		userType.addField(std::make_shared<FieldInfo<User, std::string>>("name", &User::name, FieldMetadata(FieldFlag::None)));
		userType.addField(std::make_shared<FieldInfo<User, int>>("age", &User::age, FieldMetadata(FieldFlag::None)));

		EntityDescriptor<User> userEntity("users", userType);

		SQLiteDatabase database;
		database.connect("test.db");

		MigrationManager migrations((Database&)database, executableDirectory()/"resources/migrations");
		migrations.migrate();

		EntityRegistry registry;
		registry.registerEntity(userEntity);

		EntityManager manager(database, registry);

		Repository<User> usersRepo(manager);

		User user1;
		user1.name = "Tornike";
		user1.age = 22;

		User user2;
		user2.name = "Bob";
		user2.age = 30;

		usersRepo.save(user1);
		usersRepo.save(user2);
		auto users = usersRepo.findAll();

		for (auto& user : users) {
			std::cout << user.id << " " << user.name << " " << user.age << std::endl;
		}

	} catch (const std::exception& e) {
		std::cerr << e.what() << std::endl;
	}
}