#pragma once

#include<MiniSpring.h>

#include<string>

struct User {
	int id;
	std::string username;
	std::string passwordHash;
	bool admin;

	static EntityDescriptor<User> descriptor() {
		TypeDescriptor<User> type;
		type.addField(std::make_shared<FieldInfo<User, int>>("id", &User::id, FieldMetadata(FieldFlag::PrimaryKey | FieldFlag::AutoGenerated)));
		type.addField(std::make_shared<FieldInfo<User, std::string>>("username", &User::username, FieldMetadata(FieldFlag::None)));
		type.addField(std::make_shared<FieldInfo<User, std::string>>("password_hash", &User::passwordHash, FieldMetadata(FieldFlag::None)));
		type.addField(std::make_shared<FieldInfo<User, bool>>("admin", &User::admin, FieldMetadata(FieldFlag::None)));
		return EntityDescriptor<User>("users", type);
	}
};