#pragma once

#include <string>

class Todo {
public:
	int id = 0;
	std::string title;
	bool completed = false;

	static EntityDescriptor<Todo> descriptor() {
		TypeDescriptor<Todo> type;
		type.addField(
			std::make_shared<FieldInfo<Todo, int>>("id", &Todo::id,
				FieldMetadata(
					FieldFlag::PrimaryKey |
					FieldFlag::AutoGenerated
				)));


		type.addField(std::make_shared<FieldInfo<Todo, std::string>>("title", &Todo::title, FieldMetadata(FieldFlag::None)));
		type.addField(std::make_shared<FieldInfo<Todo, bool>>("completed", &Todo::completed, FieldMetadata(FieldFlag::None)));

		return EntityDescriptor<Todo>("todos", type);
	}
};